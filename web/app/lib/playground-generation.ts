function htmlEscape(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

export function synthesizePreviewHtml(title: string, summary: string, files: PlaygroundFile[]) {
  const cssFile = files.find((file) => file.path === 'src/index.css')?.content || ''
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <style>${cssFile.slice(0, 5000)}</style>
</head>
<body>
  <main style="min-height:100vh;display:grid;place-items:center;background:#050505;color:#fafafa;font-family:ui-monospace,monospace">
    <section style="max-width:640px;padding:28px;border:1px solid #27272a">
      <h1>${htmlEscape(title)}</h1>
      <p style="color:#a1a1aa">${htmlEscape(summary)}</p>
    </section>
  </main>
</body>
</html>`
}

/** Sanitize model-provided files: allowlisted paths, per-file and total caps. */
export function sanitizeModelFiles(rawFiles: Array<{ path?: unknown; language?: unknown; content?: unknown }>): PlaygroundFile[] {
  let total = 0
  const seen = new Set<string>()
  const out: PlaygroundFile[] = []

  for (const raw of rawFiles) {
    if (out.length >= MAX_MODEL_FILES) break
    const path = normalizeFilePath(asString(raw?.path))
    const content = asString(raw?.content).slice(0, MAX_FILE_CHARS)
    if (!isModelWritablePath(path) || seen.has(path) || content.trim().length === 0) continue
    if (total + content.length > MAX_TOTAL_CHARS) break
    seen.add(path)
    total += content.length
    out.push({ path, language: asString(raw?.language).trim() || inferLanguage(path), content })
  }

  return out
}

/** Compose a complete generation from sanitized model files + scaffold. */
export function composeGeneration(params: {
  title: string
  summary: string
  modelFiles: PlaygroundFile[]
  console?: string[]
  previewHtml?: string
}): PlaygroundGeneration {
  const title = params.title.slice(0, 80) || 'Untitled'
  const summary = params.summary.slice(0, 240) || 'OpenClaude generated a project draft.'
  const files = [
    ...params.modelFiles,
    ...scaffoldFiles().filter((scaffold) => !params.modelFiles.some((file) => file.path === scaffold.path)),
  ].sort((a, b) => a.path.localeCompare(b.path))

  if (!files.some((file) => file.path === 'src/App.tsx') || !files.some((file) => file.path === 'src/index.css')) {
    throw new Error('Generation did not include editable files')
  }

  return {
    title,
    summary,
    previewHtml: params.previewHtml?.trim() || synthesizePreviewHtml(title, summary, files),
    files,
    console: (params.console ?? ['OpenClaude wrote files', 'Preview updated']).slice(0, 8),
  }
}

export function normalizeGeneration(raw: unknown): PlaygroundGeneration {
  if (!raw || typeof raw !== 'object') {
    throw new Error('Generation payload is not an object')
  }

  const value = raw as Record<string, unknown>
  const rawFiles = Array.isArray(value.files)
    ? value.files
    : value.files && typeof value.files === 'object'
      ? Object.entries(value.files as Record<string, unknown>).map(([path, content]) => (
          content && typeof content === 'object'
            ? { path, ...(content as Record<string, unknown>) }
            : { path, content }
        ))
      : [
          value.appTsx || value.app || value['src/App.tsx']
            ? { path: 'src/App.tsx', language: 'tsx', content: value.appTsx || value.app || value['src/App.tsx'] }
            : null,
          value.indexCss || value.css || value['src/index.css']
            ? { path: 'src/index.css', language: 'css', content: value.indexCss || value.css || value['src/index.css'] }
            : null,
        ].filter(Boolean)

  const modelFiles = sanitizeModelFiles(
    rawFiles.map((file) => (file && typeof file === 'object' ? (file as Record<string, unknown>) : {})),
  )

  return composeGeneration({
    title: asString(value.title, 'Untitled'),
    summary: asString(value.summary, 'OpenClaude generated a project draft.'),
    modelFiles,
    previewHtml: asString(value.previewHtml),
    console: Array.isArray(value.console)
      ? value.console.map((line) => asString(line)).filter(Boolean)
      : undefined,
  })
}

export function extractJson(text: string): unknown {
  const trimmed = text.trim()
  const parseCandidate = (candidate: string) => {
    try {
      return JSON.parse(candidate)
    } catch (error) {
      if (error instanceof SyntaxError && /Bad escaped character/.test(error.message)) {
        return JSON.parse(candidate.replace(/\\(?!["\\/bfnrtu])/g, '\\\\'))
      }
      throw error
    }
  }

  if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
    return parseCandidate(trimmed)
  }

  const fenced = trimmed.match(/```(?:json)?\s*([\s\S]*?)```/i)
  if (fenced?.[1]) {
    return parseCandidate(fenced[1].trim())
  }

  const first = trimmed.indexOf('{')
  const last = trimmed.lastIndexOf('}')
  if (first >= 0 && last > first) {
    return parseCandidate(trimmed.slice(first, last + 1))
  }

  throw new Error('Model response did not include JSON')
}

