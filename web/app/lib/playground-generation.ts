/**
 * Playground generation — shared logic for the JSON and streaming endpoints.
 *
 * Multi-file apps: besides src/App.tsx and src/index.css, the model may write
 * components, hooks, lib modules, and extra stylesheets (sanitized patterns,
 * capped count/size). Scaffold files (vite config, tsconfig, package.json…)
 * are always supplied server-side and never model-controlled.
 */

export type PlaygroundFile = {
  path: string
  language: string
  content: string
}

export type PlaygroundGeneration = {
  title: string
  summary: string
  previewHtml: string
  files: PlaygroundFile[]
  console: string[]
}

export type CurrentFile = { path: string; content: string }

export const MAX_MODEL_FILES = 16
export const MAX_FILE_CHARS = 24_000
export const MAX_TOTAL_CHARS = 200_000

const SCAFFOLD_PATHS = new Set([
  '.gitignore',
  'AGENTS.md',
  'bun.lock',
  'index.html',
  'package.json',
  'src/main.tsx',
  'src/vite-env.d.ts',
  'tsconfig.app.json',
  'tsconfig.json',
  'tsconfig.node.json',
  'vite.config.ts',
  'vercel.json',
  'README.md',
])

/** Dynamic, model-writable app files */
const DYNAMIC_FILE_RE =
  /^src\/(?:App\.tsx|index\.css|(?:components|hooks|lib)\/[A-Za-z0-9_-]{1,48}\.(?:tsx|ts)|[A-Za-z0-9_-]{1,48}\.css)$/

export function isModelWritablePath(path: string): boolean {
  return DYNAMIC_FILE_RE.test(path) && !path.includes('..')
}

export function safePath(path: string): boolean {
  if (path.includes('..') || path.startsWith('/')) return false
  return SCAFFOLD_PATHS.has(path) || DYNAMIC_FILE_RE.test(path)
}

export function normalizeFilePath(path: string) {
  const trimmed = path.trim().replace(/^\/+/, '').replace(/^\.\//, '')
  if (trimmed === 'App.tsx') return 'src/App.tsx'
  if (trimmed === 'index.css' || trimmed === 'App.css') return 'src/index.css'
  if (/^(components|hooks|lib)\//.test(trimmed)) return `src/${trimmed}`
  return trimmed
}

export function inferLanguage(path: string) {
  if (path.endsWith('.tsx')) return 'tsx'
  if (path.endsWith('.ts')) return 'typescript'
  if (path.endsWith('.css')) return 'css'
  if (path.endsWith('.json')) return 'json'
  if (path.endsWith('.html')) return 'html'
  if (path.endsWith('.md')) return 'markdown'
  return 'text'
}

function asString(value: unknown, fallback = ''): string {
  return typeof value === 'string' ? value : fallback
}

