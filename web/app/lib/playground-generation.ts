/**
 * Marker format for the streaming endpoint — far easier to parse
 * incrementally than JSON:
 *
 *   @@@TITLE: My App
 *   @@@SUMMARY: One sentence.
 *   @@@FILE: src/App.tsx
 *   ...complete file content...
 *   @@@FILE: src/index.css
 *   ...complete file content...
 *   @@@DONE
 */
export function buildStreamSystemPrompt(isIteration: boolean) {
  return `You are an app-builder assistant running inside Agentbot Playground.

${isIteration
    ? 'The user already has an app. Apply their requested changes to the CURRENT FILES provided, preserving everything they did not ask to change. Output ALL files of the app, complete and updated.'
    : "Build a polished React app from the user's request."}

Respond in EXACTLY this plain-text format (no markdown, no code fences):

@@@TITLE: <short project title>
@@@SUMMARY: <one sentence>
@@@FILE: src/App.tsx
<complete file content>
@@@FILE: src/index.css
<complete file content>
@@@DONE

${FILE_RULES}
- Every file starts with an @@@FILE: line and runs until the next @@@ marker.
- Finish with @@@DONE on its own line.`
}

export function buildUserPrompt(prompt: string, currentFiles?: CurrentFile[]) {
  if (currentFiles && currentFiles.length > 0) {
    const fileBlocks = currentFiles
      .map((file) => `--- CURRENT FILE: ${file.path} ---\n${file.content.slice(0, 12_000)}`)
      .join('\n\n')
    return `Apply this change to the existing app:\n\n${prompt}\n\n${fileBlocks}\n\nReturn ALL app files, complete and updated.`
  }
  return `Create this app in the playground:\n\n${prompt}`
}

/**
 * Edit-mode (Fast Apply path): the model returns only the changed regions per
 * file as lazy edits with "// ... existing code ..." placeholders. The server
 * then Fast-Applies each edit against the current file — far cheaper than asking
 * the model to re-emit whole files on every follow-up.
 */
export type EditInstruction = { path: string; edit: string }

export function buildEditSystemPrompt() {
  return `You are editing an existing React app in Agentbot Playground.

Return ONLY valid JSON. No markdown fences. Shape:
{
  "title": "<short title>",
  "summary": "<one sentence describing the change>",
  "edits": [
    { "path": "src/App.tsx", "edit": "<lazy edit>" }
  ]
}

Lazy edit rules:
- Include ONLY the files you change. Do not touch files that don't need changes.
- In each edit, show the changed lines in context and replace unchanged regions
  with a single line: // ... existing code ...
- Keep enough surrounding lines that the change is unambiguous.
- Valid paths: src/App.tsx, src/index.css, src/components/<Name>.tsx,
  src/hooks/<name>.ts, src/lib/<name>.ts, src/<name>.css.
- Only react and react-dom are available. No other packages.
- JSON strings must escape newlines correctly.`
}

export function buildEditUserPrompt(prompt: string, currentFiles: CurrentFile[]) {
  const fileBlocks = currentFiles
    .map((file) => `--- CURRENT FILE: ${file.path} ---\n${file.content.slice(0, 12_000)}`)
    .join('\n\n')
  return `Make this change to the app:\n\n${prompt}\n\n${fileBlocks}\n\nReturn only the lazy edits for the files you change.`
}

/** Parse the edit-mode JSON payload into validated instructions. */
export function parseEditInstructions(raw: unknown): { title: string; summary: string; edits: EditInstruction[] } {
  if (!raw || typeof raw !== 'object') throw new Error('Edit payload is not an object')
  const value = raw as Record<string, unknown>
  const rawEdits = Array.isArray(value.edits) ? value.edits : []
  const edits: EditInstruction[] = []
  for (const entry of rawEdits) {
    if (!entry || typeof entry !== 'object') continue
    const e = entry as Record<string, unknown>
    const path = normalizeFilePath(asString(e.path))
    const edit = asString(e.edit)
    if (isModelWritablePath(path) && edit.trim().length > 0) edits.push({ path, edit })
  }
  return {
    title: asString(value.title, 'Untitled'),
    summary: asString(value.summary, 'Applied your changes.'),
    edits,
  }
}

/** Parse current-files payload from a request body (iteration mode). */
export function sanitizeCurrentFiles(raw: unknown): CurrentFile[] {
  if (!Array.isArray(raw)) return []
  let total = 0
  const out: CurrentFile[] = []
  for (const entry of raw as unknown[]) {
    if (out.length >= MAX_MODEL_FILES) break
    const file = entry as { path?: unknown; content?: unknown }
    const path = normalizeFilePath(asString(file?.path))
    const content = asString(file?.content)
    if (!isModelWritablePath(path) || content.length === 0) continue
    if (total + content.length > MAX_TOTAL_CHARS) break
    total += content.length
    out.push({ path, content })
  }
  return out
}

/**
 * Incremental parser for the @@@ marker stream format.
 * Feed chunks; it emits events and keeps partial state.
 */
export class MarkerStreamParser {
  private buffer = ''
  title = ''
  summary = ''
  files: { path: string; content: string }[] = []
  private currentPath: string | null = null
  done = false

  /** Returns events produced by this chunk. */
  push(chunk: string): Array<
    | { type: 'meta'; title: string; summary: string }
    | { type: 'file_open'; path: string }
    | { type: 'file_chunk'; path: string; text: string }
    | { type: 'file_close'; path: string; content: string }
    | { type: 'done' }
  > {
    this.buffer += chunk
    const events: ReturnType<MarkerStreamParser['push']> = []

    // Process complete lines; hold back the last partial line unless it can't
    // be a marker prefix (so file content streams promptly).
    while (true) {
      const newline = this.buffer.indexOf('\n')
      if (newline === -1) {
        // Flush non-marker partials into the open file for live streaming
        if (this.currentPath && this.buffer.length > 0 && !'@@@'.startsWith(this.buffer.slice(0, 3)) && !this.buffer.startsWith('@')) {
          events.push({ type: 'file_chunk', path: this.currentPath, text: this.buffer })
          this.appendToCurrent(this.buffer)
          this.buffer = ''
        }
        break
      }

      const line = this.buffer.slice(0, newline)
      this.buffer = this.buffer.slice(newline + 1)

      if (line.startsWith('@@@TITLE:')) {
        this.title = line.slice('@@@TITLE:'.length).trim()
        if (this.summary) events.push({ type: 'meta', title: this.title, summary: this.summary })
      } else if (line.startsWith('@@@SUMMARY:')) {
        this.summary = line.slice('@@@SUMMARY:'.length).trim()
        events.push({ type: 'meta', title: this.title, summary: this.summary })
      } else if (line.startsWith('@@@FILE:')) {
        this.closeCurrent(events)
        const path = normalizeFilePath(line.slice('@@@FILE:'.length).trim())
        if (isModelWritablePath(path)) {
          this.currentPath = path
          this.files.push({ path, content: '' })
          events.push({ type: 'file_open', path })
        } else {
          this.currentPath = null
        }
      } else if (line.startsWith('@@@DONE')) {
        this.closeCurrent(events)
        this.done = true
        events.push({ type: 'done' })
      } else if (this.currentPath) {
        const text = `${line}\n`
        events.push({ type: 'file_chunk', path: this.currentPath, text })
        this.appendToCurrent(text)
      }
    }

    return events
  }

  private appendToCurrent(text: string) {
    const file = this.files.find((item) => item.path === this.currentPath)
    if (file && file.content.length < MAX_FILE_CHARS) file.content += text
  }

  private closeCurrent(events: ReturnType<MarkerStreamParser['push']>) {
    if (!this.currentPath) return
    const file = this.files.find((item) => item.path === this.currentPath)
    if (file) {
      file.content = file.content.replace(/\n$/, '\n')
      events.push({ type: 'file_close', path: file.path, content: file.content })
    }
    this.currentPath = null
  }

  toGeneration(): PlaygroundGeneration {
    const modelFiles = sanitizeModelFiles(this.files.map((file) => ({ ...file, language: inferLanguage(file.path) })))
    return composeGeneration({
      title: this.title || 'Untitled',
      summary: this.summary || 'OpenClaude generated a project draft.',
      modelFiles,
      console: ['OpenClaude streamed files', 'Preview updated live'],
    })
  }
}
